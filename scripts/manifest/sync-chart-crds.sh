#!/usr/bin/env bash
#
# Single source of truth for the Helm chart's CRD templates (Q73 / Q142 slice A).
#
# The charts ship every CRD as a template, but the authoritative schema is the
# controller-gen output under api/config/crd, from the neutral api module.
# Hand-copying invites silent drift: a field added to a CRD type but not
# propagated to the chart copy is silently pruned at apply time. This script
# regenerates the chart copies FROM the controller-gen sources, injecting the
# per-CRD `helm.sh/resource-policy: keep` annotation the chart needs (so
# `helm upgrade` carries field changes and `helm uninstall` preserves the CRD).
#
#   scripts/manifest/sync-chart-crds.sh            # write the chart CRD templates (make chart-crds)
#   scripts/manifest/sync-chart-crds.sh --check    # fail if the chart copies are stale (make chart-crds-check)
#
# The --check mode backs the CI drift gate (manifest-validate.yml) and `make check`.
set -euo pipefail
shopt -s inherit_errexit

REPO_ROOT="$(git rev-parse --show-toplevel)"
cd "$REPO_ROOT"
# shellcheck source=scripts/lib/chart-sync.sh
source "$REPO_ROOT/scripts/lib/chart-sync.sh"

# Per-CRD annotation block injected after the controller-gen version line. Kept
# here (not in the chart copies) so the chart files are fully generated.
#
# The only CRD in the chart-root crds/ dir rather than templates/crds/, and the
# only one carrying no resource-policy: keep — Helm never deletes crds/ anyway, so
# the uninstall-preservation the other CRDs need that annotation for is already the
# default here. No Helm templating may appear in this block: Helm does not render
# crds/. See the add_crd call for why this CRD cannot live in templates/.
PRIORITYCLASSALLOWLIST_BLOCK="$(cat <<'EOF'
    # DO NOT hand-edit: generated by scripts/manifest/sync-chart-crds.sh from the
    # controller-gen output under api/config/crd.
    #
    # This CRD ships in the chart-root crds/ dir, unlike every other CRD in this
    # repo, because the chart also renders a PriorityClassAllowlist CR (the
    # priorityclass-allowlist-guard policy's param). Helm resolves REST mappings
    # for the entire manifest BEFORE applying any of it, so a CR whose CRD is a
    # template in the same release fails the install outright with "no matches for
    # kind". Only crds/ is installed ahead of that resolution.
    #
    # The cost lands on UPGRADES, which skip crds/ entirely. The documented
    # upgrade procedure therefore applies the chart's CRDs unconditionally
    # (`helm show crds <chart> | kubectl apply -f -`), so a field added here
    # reaches existing releases without a release-note callout — and the chart
    # preflights the kind and fails with that command if it is skipped. Without
    # that step the apiserver silently prunes a new field from the rendered CR.
    # See docs/operations/upgrade.md.
EOF
)"
V2_BLOCK="$(cat <<'EOF'
    # Sourced from the controller-gen output under cmd/*/config/crd (do not
    # hand-edit). Shipped under templates/crds/ with resource-policy: keep so
    # day-2 `helm upgrade` carries CRD field changes and `helm uninstall`
    # preserves every tenant's v2 (actions-gateway.com) objects.
    helm.sh/resource-policy: keep
{{- if .Values.conversion.certManager.enabled }}
    # cert-manager's ca-injector copies the GMC webhook serving CA into the
    # spec.conversion.webhook.clientConfig.caBundle below (Q74 conversion webhook).
    cert-manager.io/inject-ca-from: {{ printf "%s/%s" (.Values.conversion.webhook.service.namespace | default .Release.Namespace) .Values.conversion.certManager.certificateName }}
{{- end }}
EOF
)"

# spec.conversion block injected under `spec:` for the v2 CRDs only (Q74). The v2
# kinds are multi-version — v2beta1 is the hub, v2alpha1 and v2 the spokes, and v2
# the storage version — so the apiserver must call the GMC-hosted /convert webhook to serve
# or admit any version. controller-gen emits no conversion stanza (the authoritative
# api/config/crd output stays deployment-agnostic and conversion-free), so this
# deployment wiring is injected here, mirroring how sync-chart-webhook.sh re-injects
# the validating webhook's Helm wiring. The clientConfig points at the GMC webhook
# Service shipped by the main actions-gateway chart.
V2_CONVERSION_BLOCK="$(cat <<'EOF'
  conversion:
    strategy: Webhook
    webhook:
      conversionReviewVersions:
      - v1
      clientConfig:
        service:
          name: {{ .Values.conversion.webhook.service.name }}
          namespace: {{ .Values.conversion.webhook.service.namespace | default .Release.Namespace }}
          path: /convert
          port: {{ int .Values.conversion.webhook.service.port }}
{{- if and (not .Values.conversion.certManager.enabled) .Values.conversion.caBundle }}
        caBundle: {{ .Values.conversion.caBundle }}
{{- end }}
EOF
)"

# Parallel arrays describing every chart CRD template: controller-gen source,
# chart destination, and the annotation block to inject. A single add_crd call
# registers one CRD; sync() and check() both iterate this table.
CRD_SRCS=()
CRD_DSTS=()
CRD_BLOCKS=()
CRD_CONVERSIONS=()

add_crd() { # add_crd SRC DST BLOCK [CONVERSION_BLOCK]
	CRD_SRCS+=("$1")
	CRD_DSTS+=("$2")
	CRD_BLOCKS+=("$3")
	CRD_CONVERSIONS+=("${4:-}")
}

# PriorityClassAllowlist (Q492) — two deviations from the layout of every other
# CRD here, each forced:
#
#  1. It is an actions-gateway.com kind that ships in the MAIN chart, not the
#     opt-in actions-gateway-crds-v2 chart. It is the paramKind of the
#     priorityclass-allowlist-guard policy, which admissionPolicy.enabled defaults
#     ON, so a main-chart install that could not create this CRD would render a
#     policy whose params can never resolve — and parameterNotFoundAction: Deny
#     turns that into a cluster-wide denial of every
#     runnersets/runnertemplates write. The 1 MiB release-Secret
#     budget that forced the v2 split is not at risk: this CRD is a list of
#     strings (~4 KB), not an embedded PodTemplateSpec (~600 KB).
#  2. It ships in the chart-root crds/ dir, not templates/crds/, because the same
#     release also renders a PriorityClassAllowlist CR. See the block above.
#
# Served at v2beta1 and v2 (storage) with identical schemas, so no conversion block:
# the apiserver's default None strategy rewrites apiVersion alone.
add_crd "api/config/crd/actions-gateway.com_priorityclassallowlists.yaml" \
	"charts/actions-gateway/crds/priorityclassallowlist-crd.yaml" \
	"$PRIORITYCLASSALLOWLIST_BLOCK"

# v2alpha1 — actions-gateway.com (Q149). Shipped by the SEPARATE, opt-in
# actions-gateway-crds-v2 chart, not the main chart: the RunnerTemplate /
# ClusterRunnerTemplate CRDs each embed a full PodTemplateSpec (~600 KB), and
# adding them to the main chart pushed its Helm release Secret past the hard 1 MiB
# limit (Helm stores the rendered manifest + a copy of the chart source, gzipped,
# in one Secret). A separate release keeps each chart within budget and makes v2
# opt-in. All five v2 kinds (ActionsGateway, EgressProxy, RunnerSet,
# RunnerTemplate, ClusterRunnerTemplate) live in the neutral api/ module, whose
# controller-gen output under api/config/crd is the single source.
V2_CHART="charts/actions-gateway-crds-v2/templates/crds"
add_crd "api/config/crd/actions-gateway.com_actionsgateways.yaml" \
	"$V2_CHART/actionsgateway-crd.yaml" "$V2_BLOCK" "$V2_CONVERSION_BLOCK"
add_crd "api/config/crd/actions-gateway.com_egressproxies.yaml" \
	"$V2_CHART/egressproxy-crd.yaml" "$V2_BLOCK" "$V2_CONVERSION_BLOCK"
add_crd "api/config/crd/actions-gateway.com_runnersets.yaml" \
	"$V2_CHART/runnerset-crd.yaml" "$V2_BLOCK" "$V2_CONVERSION_BLOCK"
add_crd "api/config/crd/actions-gateway.com_runnertemplates.yaml" \
	"$V2_CHART/runnertemplate-crd.yaml" "$V2_BLOCK" "$V2_CONVERSION_BLOCK"
add_crd "api/config/crd/actions-gateway.com_clusterrunnertemplates.yaml" \
	"$V2_CHART/clusterrunnertemplate-crd.yaml" "$V2_BLOCK" "$V2_CONVERSION_BLOCK"

# render SRC DST BLOCK — copy SRC to DST, inserting BLOCK right after the
# `controller-gen.kubebuilder.io/version:` annotation line. BLOCK is passed
# through the environment (ENVIRON), not `-v`: a multi-line `-v` assignment is
# rejected by BSD awk (macOS), while ENVIRON is portable across BSD awk and gawk.
render() {
	local src="$1" dst="$2" block="$3" conversion="${4:-}"
	mkdir -p "$(dirname "$dst")"
	BLOCK="$block" CONVERSION="$conversion" awk '
		{ print }
		!injected && /^    controller-gen\.kubebuilder\.io\/version:/ {
			printf "%s\n", ENVIRON["BLOCK"]
			injected = 1
		}
		# For the v2 CRDs, inject the deployment-specific spec.conversion block
		# immediately after the top-level `spec:` line (Q74). CONVERSION is empty for
		# the PriorityClassAllowlist CRD, so this is a no-op there.
		!conv_injected && ENVIRON["CONVERSION"] != "" && /^spec:$/ {
			printf "%s\n", ENVIRON["CONVERSION"]
			conv_injected = 1
		}
		END {
			if (!injected) {
				print "sync-chart-crds: no controller-gen version line found in source" > "/dev/stderr"
				exit 1
			}
			if (ENVIRON["CONVERSION"] != "" && !conv_injected) {
				print "sync-chart-crds: no top-level spec: line found for conversion injection" > "/dev/stderr"
				exit 1
			}
		}
	' "$src" > "$dst"
}

sync() {
	local i
	for i in "${!CRD_SRCS[@]}"; do
		render "${CRD_SRCS[$i]}" "${CRD_DSTS[$i]}" "${CRD_BLOCKS[$i]}" "${CRD_CONVERSIONS[$i]}"
	done
	echo "wrote ${#CRD_DSTS[@]} chart CRD templates from controller-gen sources."
}

# check renders each chart CRD to a temp file and compares it against the on-disk
# chart copy — it does NOT mutate the working tree, so it detects any drift in the
# committed chart (and any uncommitted hand-edit), not just whether a regen-in-place
# produced a git diff.
check() {
	local rc=0 i tmp
	for i in "${!CRD_SRCS[@]}"; do
		tmp="$(chart_sync_mktemp)"
		render "${CRD_SRCS[$i]}" "$tmp" "${CRD_BLOCKS[$i]}" "${CRD_CONVERSIONS[$i]}"
		if ! diff -u "${CRD_DSTS[$i]}" "$tmp"; then
			echo "ERROR: ${CRD_DSTS[$i]} is out of sync with ${CRD_SRCS[$i]}." >&2
			echo "Re-sync and commit: make chart-crds" >&2
			rc=1
		fi
	done
	if [[ "$rc" -ne 0 ]]; then
		exit 1
	fi
	echo "chart CRD templates are in sync."
}

chart_sync_main "$@"
